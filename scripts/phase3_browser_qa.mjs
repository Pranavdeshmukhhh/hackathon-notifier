// Run only against scripts/preview_api.py and the local Vite server.
import {chromium,launchOptions} from './browser_runtime.mjs';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const out=process.env.BROWSER_ARTIFACT_DIR || new URL('../artifacts/',import.meta.url).pathname;
await fs.mkdir(out,{recursive:true});
const browser=await chromium.launch(launchOptions);
const errors=[];
try{
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();page.on('pageerror',error=>errors.push(error.message));
 const requests=[];page.on('request',request=>{if(request.url().includes('/api/'))requests.push(request.url());});
 await page.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
 await page.getByRole('article').first().waitFor();
 await page.evaluate(()=>document.fonts.ready);
 assert.equal(await page.evaluate(()=>document.fonts.check('14px Geist')),true);
 assert.equal(requests.some(url=>url.includes('status=closing&tab=upcoming&sort=deadline&limit=3')),true);
 const titles=await page.getByRole('article').getByRole('heading',{level:2}).allTextContents();
 const map=page.getByRole('region',{name:'Opportunity signal map'});
 assert.equal(await map.getByText('12 on this page').count(),1);
 const options=await map.getByRole('combobox').locator('option').allTextContents();
 assert.equal(options.every(title=>titles.includes(title)),true);
 await page.screenshot({path:`${out}/phase3-desktop-dark.png`,animations:'disabled'});
 const select=map.getByRole('combobox',{name:'Choose a mapped opportunity'});
 const selection=await select.locator('option').last().getAttribute('value');
 const selectedTitle=await select.locator('option').last().textContent();
 await select.selectOption(selection);
 await map.getByRole('button',{name:'Open selected opportunity'}).click();
 const dialog=page.getByRole('dialog',{name:selectedTitle});await dialog.waitFor();
 assert.equal(new URL(page.url()).searchParams.get('event'),selection);
 assert.equal(await dialog.getByText('Source facts, in context').count(),1);
 await page.screenshot({path:`${out}/phase3-detail-dark.png`,animations:'disabled'});
 await page.keyboard.press('Escape');
 assert.equal(await map.getByRole('button',{name:'Open selected opportunity'}).evaluate(el=>el===document.activeElement),true);
 await page.getByRole('searchbox').fill('Fintech');
 await page.waitForFunction(()=>document.querySelectorAll('article').length===4);
 await page.getByRole('region',{name:'Closing registration windows'}).getByRole('button',{name:/View closing soon/}).click();
 await page.waitForFunction(()=>new URL(location.href).searchParams.get('status')==='closing');
 await page.waitForFunction(()=>document.querySelectorAll('article').length===4 && document.querySelector('article h2')?.textContent.includes('Build for Tomorrow'));
 assert.equal(new URL(page.url()).searchParams.has('q'),false);
 await page.getByRole('button',{name:'Explore',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('article').length===12);
 await page.getByRole('button',{name:'Compact row view'}).click();
 assert.equal(await page.locator('article.hn-card-row-mode').count(),12);
 await page.getByRole('button',{name:'Card grid view'}).click();
 await page.getByRole('button',{name:'Switch to light mode'}).click();
 assert.equal(await page.evaluate(()=>document.querySelector('meta[name="theme-color"]').content),'#f3f4ef');
 await page.screenshot({path:`${out}/phase3-desktop-light.png`,animations:'disabled'});
 await page.reload({waitUntil:'networkidle'});
 assert.equal(await page.locator('html').getAttribute('data-theme'),'light');
 await page.getByRole('contentinfo').getByRole('button',{name:'How it works',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 await page.screenshot({path:`${out}/phase3-guide-light.png`,animations:'disabled'});
 await page.keyboard.press('Escape');
 for(const width of [320,390,768,1024,1440]){
  await page.setViewportSize({width,height:900});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,`overflow at ${width}`);
  await page.evaluate(()=>window.scrollTo({top:1800,behavior:'instant'}));
  const sticky=await page.evaluate(()=>({header:{top:document.querySelector('.hn-header').getBoundingClientRect().top,bottom:document.querySelector('.hn-header').getBoundingClientRect().bottom},controls:{top:document.querySelector('.hn-controls').getBoundingClientRect().top}}));
  assert.equal(Math.round(sticky.header.top),0,`header does not stick at ${width}`);
  assert.equal(Math.round(sticky.controls.top),Math.round(sticky.header.bottom),`toolbar overlaps header at ${width}`);
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
 }
 await context.close();
 const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'});
 const phone=await mobile.newPage();phone.on('pageerror',error=>errors.push(error.message));
 await phone.goto('http://127.0.0.1:5173/',{waitUntil:'networkidle'});
 await phone.getByRole('article').first().waitFor();
 await phone.screenshot({path:`${out}/phase3-mobile-dark.png`,animations:'disabled'});
 await phone.getByRole('button',{name:'Explore the deadline map'}).click();
 await phone.getByRole('combobox',{name:'Choose a mapped opportunity'}).waitFor({state:'visible'});
 await phone.screenshot({path:`${out}/phase3-mobile-map.png`,animations:'disabled'});
 await phone.getByRole('button',{name:'Open selected opportunity'}).click();await phone.getByRole('dialog').waitFor();
 assert.equal(await phone.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await phone.screenshot({path:`${out}/phase3-mobile-detail.png`,animations:'disabled'});
 await phone.keyboard.press('Escape');
 await phone.getByRole('button',{name:'Explore the deadline map'}).click();
 await phone.getByRole('button',{name:'Switch to light mode'}).click();
 await phone.screenshot({path:`${out}/phase3-mobile-light.png`,animations:'disabled'});
 await phone.getByRole('button',{name:'Filters',exact:true}).click();
 await phone.getByRole('combobox',{name:'Sort hackathons'}).selectOption('newest');
 await phone.waitForFunction(()=>new URL(location.href).searchParams.get('sort')==='newest');
 assert.equal(await phone.locator('article').first().evaluate(el=>getComputedStyle(el).animationName),'none');
 await mobile.close();
 assert.deepEqual(errors,[]);
 console.log('PHASE 3 BROWSER QA PASSED: real-data map selection, closing filter, row layout, theme persistence, local fonts, guide/detail dialogs, 320–1440px overflow and sticky navigation, mobile map and reduced motion.');
}finally{await browser.close();}
